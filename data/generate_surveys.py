def gender(text: str, agent_f: int, cust_f: int) -> str:
    text = re.sub(r"\[([^|\]]*)\|([^\]]*)\]", lambda m: m.group(agent_f + 1), text)
    return re.sub(r"<([^|>]*)\|([^>]*)>", lambda m: m.group(cust_f + 1), text)


def build(sentiment: str, cust_f: int) -> str:
    w = {"pos": random.randint(2, 5), "mix": random.randint(8, 20), "neg": random.randint(25, 60)}[sentiment]
    ch, t = random.choice(CHANNELS), random.choice(TOPICS)
    a, agent_f = random.choice(AGENTS)
    paras = [random.choice(OPEN[sentiment]).format(ch=ch, t=t, w=w),
             random.choice(AGENT[sentiment]).format(a=a),
             random.choice(RESOLVE[sentiment])]
    if random.random() < 0.6:
        paras.append(random.choice(CLOSE[sentiment]))
    return gender("\n\n".join(paras), agent_f, cust_f)


def main() -> None:
    start = date(2025, 1, 1)
    span = (date(2026, 11, 20) - start).days
    rows = []
    for i in range(1, ROWS + 1):
        sentiment = random.choices(["pos", "mix", "neg"], weights=[45, 30, 25])[0]
        first = random.choice(FIRST)
        rows.append({
            "survey_id": f"S{i:05d}",
            "customer_name": f"{first} {random.choice(LAST)}",
            "survey_date": (start + timedelta(days=random.randint(0, span))).isoformat(),
            "experience": build(sentiment, int(first in FEMALE_FIRST)),
        })
    rows.sort(key=lambda r: r["survey_date"])
    with OUT.open("w", encoding="utf-8-sig", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=list(rows[0]), quoting=csv.QUOTE_ALL)
        wr.writeheader()
        wr.writerows(rows)
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
